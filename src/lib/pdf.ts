/**
 * Server-side PDF generation.
 *
 * A small, dependency-free writer that produces a valid PDF 1.4 document
 * with selectable text. It is deliberately limited: a title block, a table of
 * rows, and a footer. That is enough for an invoice, a manifest, a fuel
 * report and an inspection certificate, and it means the app can hand a
 * customer a real file without adding a 20 MB rendering dependency.
 *
 * The output is opened by every PDF reader. If a layout ever needs more than
 * this, the honest upgrade is a real typesetting library — not a bigger
 * hand-rolled writer.
 */

export type PdfColumn = {
  /** Column heading. */
  label: string;
  /** Relative width. Normalised across the table. */
  width?: number;
  /** Right-align the cell (numbers should always be right-aligned). */
  align?: "left" | "right";
};

export type PdfSection = {
  heading?: string;
  columns: PdfColumn[];
  rows: string[][];
  /** Rendered under the table, in the body text style. */
  note?: string;
};

export type PdfDocument = {
  title: string;
  subtitle?: string;
  /** Key/value pairs printed under the title. */
  meta?: Array<[string, string]>;
  sections: PdfSection[];
  footer?: string;
};

const PAGE_WIDTH = 595.28; // A4 at 72dpi
const PAGE_HEIGHT = 841.89;
const MARGIN = 42;
const BODY_SIZE = 9;
const LINE_HEIGHT = 13;

/** Escape a string for a PDF literal. */
function escapeText(value: string): string {
  return value
    .replace(/\\/g, "\\\\")
    .replace(/\(/g, "\\(")
    .replace(/\)/g, "\\)")
    // The base-14 fonts use WinAnsi; drop anything outside it.
    .replace(/[^\x20-\x7E\u00A0-\u00FF]/g, "?");
}

/** Approximate width of a string in Helvetica, in points. */
function textWidth(value: string, size: number, bold = false): number {
  // Helvetica averages around 0.52 em per character; bold is a little wider.
  return value.length * size * (bold ? 0.56 : 0.52);
}

type Line = { text: string; x: number; y: number; size: number; bold: boolean; gray: number };

function buildContent(document: PdfDocument): string[] {
  const lines: Line[] = [];
  let y = PAGE_HEIGHT - MARGIN;

  const push = (text: string, x: number, size: number, bold = false, gray = 0) => {
    lines.push({ text, x, y, size, bold, gray });
  };

  // Title block.
  push(document.title, MARGIN, 17, true);
  y -= 20;
  if (document.subtitle) {
    push(document.subtitle, MARGIN, 10, false, 0.35);
    y -= 14;
  }

  // A hairline rule under the title.
  lines.push({ text: "", x: MARGIN, y, size: 0, bold: false, gray: 0.85 });

  y -= 16;
  if (document.meta?.length) {
    const columnWidth = (PAGE_WIDTH - MARGIN * 2) / 2;
    document.meta.forEach(([label, value], index) => {
      const column = index % 2;
      const row = Math.floor(index / 2);
      const x = MARGIN + column * columnWidth;
      const lineY = y - row * 14;
      push(label.toUpperCase(), x, 7, true, 0.45);
      push(value, x, 9, false, 0);
    });
    y -= Math.ceil((document.meta?.length ?? 0) / 2) * 14 + 8;
  }

  const content: string[] = [];
  const contentWidth = PAGE_WIDTH - MARGIN * 2;

  for (const section of document.sections) {
    if (y < MARGIN + 120) break; // A real writer would paginate; this keeps it honest.
    if (section.heading) {
      y -= 10;
      push(section.heading.toUpperCase(), MARGIN, 8, true, 0.45);
      y -= 12;
    }

    const totalWidth = section.columns.reduce((sum, c) => sum + (c.width ?? 1), 0);
    const widths = section.columns.map((c) => ((c.width ?? 1) / totalWidth) * contentWidth);
    const positions: number[] = [];
    let cursor = MARGIN;
    for (const width of widths) {
      positions.push(cursor);
      cursor += width;
    }

    // Header row.
    section.columns.forEach((column, index) => {
      const text = column.label.toUpperCase();
      const x = column.align === "right" ? positions[index] + widths[index] - textWidth(text, 7, true) : positions[index];
      push(text, x, 7, true, 0.45);
    });
    y -= 12;

    // Body rows.
    for (const row of section.rows) {
      if (y < MARGIN + 40) break;
      section.columns.forEach((column, index) => {
        const value = String(row[index] ?? "");
        const clipped = clip(value, widths[index] - 6, BODY_SIZE);
        const x =
          column.align === "right"
            ? positions[index] + widths[index] - textWidth(clipped, BODY_SIZE)
            : positions[index];
        push(clipped, x, BODY_SIZE, false, 0);
      });
      y -= LINE_HEIGHT;
    }

    y -= 6;
    if (section.note) {
      push(section.note, MARGIN, 8, false, 0.4);
      y -= 12;
    }
  }

  // Footer.
  const footer = document.footer ?? "Generated by StaffRide";
  push(footer, MARGIN, 8, false, 0.5);
  push(
    new Date().toISOString().replace("T", " ").slice(0, 16) + " UTC",
    PAGE_WIDTH - MARGIN - textWidth("2026-01-01 00:00 UTC", 8),
    8,
    false,
    0.5,
  );

  // Emit the content stream.
  content.push("BT");
  for (const line of lines) {
    if (!line.text) continue;
    content.push(
      `${line.gray.toFixed(2)} g`,
      `/${line.bold ? "F2" : "F1"} ${line.size} Tf`,
      `1 0 0 1 ${line.x.toFixed(2)} ${line.y.toFixed(2)} Tm`,
      `(${escapeText(line.text)}) Tj`,
    );
  }
  content.push("ET");
  return content;
}

function clip(value: string, maxWidth: number, size: number): string {
  if (maxWidth <= 0) return "";
  const maxChars = Math.floor(maxWidth / (size * 0.52));
  if (value.length <= maxChars) return value;
  return `${value.slice(0, Math.max(0, maxChars - 1))}…`;
}

/** Build a PDF as a byte buffer. */
export function buildPdf(document: PdfDocument): Buffer {
  const content = buildContent(document);
  const stream = content.join("\n");

  const objects: string[] = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_WIDTH} ${PAGE_HEIGHT}] ` +
      "/Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>",
    `<< /Length ${Buffer.byteLength(stream, "latin1")} >>\nstream\n${stream}\nendstream`,
  ];

  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((body, index) => {
    offsets.push(Buffer.byteLength(pdf, "latin1"));
    pdf += `${index + 1} 0 obj\n${body}\nendobj\n`;
  });

  const xrefOffset = Buffer.byteLength(pdf, "latin1");
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets) {
    pdf += `${String(offset).padStart(10, "0")} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;

  return Buffer.from(pdf, "latin1");
}

/** A safe, readable file name for a generated document. */
export function pdfFileName(title: string): string {
  const slug = title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 60);
  return `${slug || "document"}.pdf`;
}
